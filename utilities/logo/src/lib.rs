#![no_std]
#![deny(missing_docs)]

use core::{cell::UnsafeCell, fmt::Write};

// Big enough for our Mode 12 (320 x 480 @ 8bpp) logo
struct RacyBuffer {
    inner: UnsafeCell<[u8; 320 * 480]>,
}

unsafe impl Sync for RacyBuffer {}

static FRAMEBUFFER: RacyBuffer = RacyBuffer {
    inner: UnsafeCell::new(*include_bytes!("logo.raw")),
};

/// Entry point to the program
pub fn main() -> i32 {
    let mut stdout = neotron_sdk::stdout();

    // try 12 for 480-line mode, or 28 for 400-line mode
    let Some(mode) = neotron_sdk::VideoMode::try_from_u8(12) else {
        _ = writeln!(stdout, "Invalid mode");
        return -1;
    };

    let handle: Result<_, _> = neotron_sdk::File::open(
        neotron_sdk::path::Path::new("GFX:").unwrap(),
        neotron_sdk::Flags::WRITE,
    );
    let Ok(handle) = handle else {
        return -1;
    };
    unsafe {
        // point at our canned data
        if handle
            .ioctl(
                neotron_sdk::ioctls::gfx::COMMAND_CHANGE_MODE,
                neotron_sdk::ioctls::gfx::change_mode_value(
                    mode,
                    FRAMEBUFFER.inner.get() as *mut u32,
                ),
            )
            .is_err()
        {
            return -2;
        }
    }

    for (index, entry) in PALETTE.iter().enumerate() {
        unsafe {
            // load the palette
            if handle
                .ioctl(
                    neotron_sdk::ioctls::gfx::COMMAND_SET_PALETTE,
                    neotron_sdk::ioctls::gfx::set_palette_value(
                        index as u8,
                        entry.0,
                        entry.1,
                        entry.2,
                    ),
                )
                .is_err()
            {
                return -2;
            }
        }
    }

    wait_for_key_while_rolling(&handle);

    0
}

fn wait_for_key_while_rolling(handle: &neotron_sdk::File) {
    let stdin = neotron_sdk::stdin();
    let mut buffer = [0u8; 1];
    let mut indexes = (START_ROLL..=END_ROLL).cycle();
    while let Ok(0) = stdin.read(&mut buffer) {
        for entry in PALETTE.iter().skip(START_ROLL) {
            // roll the palette.
            // each time around each palette entry goes in one place higher
            unsafe {
                if handle
                    .ioctl(
                        neotron_sdk::ioctls::gfx::COMMAND_SET_PALETTE,
                        neotron_sdk::ioctls::gfx::set_palette_value(
                            indexes.next().unwrap() as u8,
                            entry.0,
                            entry.1,
                            entry.2,
                        ),
                    )
                    .is_err()
                {
                    return;
                }
            }
        }
        // this causes the offset so it rolls
        _ = indexes.next();
        neotron_sdk::delay(core::time::Duration::from_millis(100));
    }
}

